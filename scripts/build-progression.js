import {progressive} from './lib/progression.js';
import fs from 'node:fs';import{levels,buildLevel,LEVEL_SPECS}from'../src/levels.js';import{initial,solve}from'../src/rules.js';import{heapOf}from'../src/pile.js';import{layers,progression,opening,replay,rng}from'./lib/level-metrics.js';
const generated={};

function pack(l,r,meta){return{...meta,slots:l.slots,hand:l.bottles.filter(b=>b.hand).length,heap:l.bottles.filter(b=>!b.hand).map(b=>[b.colors,b.heap.x,b.heap.z,b.heap.yaw]),progression:progression(l),solution:r.path,searchNodes:r.nodes};}
// Keep the original 004 snapshot in docs; changing progression changes its data.
for(const idx of[2,3]){
 const base=buildLevel({...LEVEL_SPECS[idx],procedural:true});let found=null;
 for(let trial=0;trial<16;trial++){
  const l=progressive(base,trial<8?'neutral':'wide',1900+trial),r=solve(initial(l),l,12000,450);
  console.log(`progressive ${idx+1} trial ${trial}: ${r.path?.length??'unknown'} / ${r.nodes}`);
  if(r.path){replay(l,r.path);found=pack(l,r,{version:'progressive-v1',sourceSeed:idx===2?8:8});break;}
 }
 if(!found)throw Error(`No verified progressive ${idx+1}`);generated[idx+1]=found;
}
const base=buildLevel({seed:8,totals:[36,36,32,32,32,32],mix:{2:5,3:4,4:1}});
const h=heapOf(base,initial(base).pile);console.log('Pair geometry',h.free.size,Math.max(...[...h.poses.values()].map(p=>p.anchor.y)));
const candidates={wide:[],narrow:[]};
for(const style of['wide','narrow'])for(let trial=0;trial<12;trial++){
 const l=progressive(base,style,6100+trial),r=solve(initial(l),l,12000,500);
 console.log(`50 ${style} trial ${trial}: ${r.path?.length??'unknown'} / ${r.nodes}`);
 if(!r.path)continue;
 replay(l,r.path);const o=opening(l);console.log(' opening',o.safePaths,o.paths,o.uniformChoiceSurvival);
 candidates[style].push({l,r,o,trial});
 // First collect a few independently solvable variants, then compare safety.
 if(candidates[style].length>=3)break;
}
if(!candidates.wide.length||!candidates.narrow.length)throw Error('Missing a solvable pair');
const wide=candidates.wide.sort((a,b)=>b.o.uniformChoiceSurvival-a.o.uniformChoiceSurvival)[0],narrow=candidates.narrow.sort((a,b)=>a.o.uniformChoiceSurvival-b.o.uniformChoiceSurvival)[0];
if(wide.o.uniformChoiceSurvival-narrow.o.uniformChoiceSurvival<.12)throw Error('Pair forgiveness difference too small');
generated[5]=pack(wide.l,wide.r,{version:'forgiveness-wide-v1',trial:wide.trial,opening:wide.o});generated[6]=pack(narrow.l,narrow.r,{version:'forgiveness-narrow-v1',trial:narrow.trial,opening:narrow.o});
fs.writeFileSync('docs/level-generation.json',JSON.stringify(generated,null,2));
const runtime=Object.fromEntries(Object.entries(generated).map(([k,d])=>[k,{slots:d.slots,hand:d.hand,heap:d.heap}]));
fs.writeFileSync('src/level-data.js','// Generated by scripts/build-progression.js; legally replayed.\nexport default '+JSON.stringify(runtime,null,2)+';\n');console.log('Saved certified progressive levels 003–006');
